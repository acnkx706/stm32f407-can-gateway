#ifndef __LV_PORT_H
#define __LV_PORT_H

/*==============================================================================
 *  LVGL 移植层（F407 + ST7789 240x240 + EC11 编码器）
 *
 *  ★ 这里做两件事
 *    · 显示：把 LVGL 画好的像素块刷到屏幕上
 *    · 输入：把 EC11 的旋转量交给 LVGL，驱动焦点移动
 *
 *  ★ 为什么不在这里做编码器的按键
 *    这块 EC11 模块只引出了 A/B/C 三个编码器针，按键没引出；
 *    板上 KEY 在 PA15，默认是 JTDI，要用得先关 JTAG。
 *    所以第一版只做旋转导航，按下确认留到接线补上之后。
 *============================================================================*/

#include "lvgl.h"

/* ★ 初始化 LVGL 内核 + 显示 + 输入
 * · 必须在 LCD 初始化之后调用
 * · 内部会调用 lv_init()
 */
void lv_port_init(void);

/* ★ 取走编码器本轮的旋转增量（单位：档位，不是计数）
 * · 一格 = 4 个计数，函数内部已经除过 4
 */
int16_t lv_port_encoder_take(void);

#endif /* __LV_PORT_H */
